"""Generate test/functional/data/mweb_fixture.json.

Tests that run without a wallet can't make MWEB transactions, so they load a
chain and transactions made here once, with a wallet (load_mweb_fixture):

- blocks 1 to FIRST_MWEB_HEIGHT - 1, mined at a fixed mock time to fixed
  addresses, so tests mine them again instead of storing them;
- the MWEB blocks: the first one confirms a peg-in of four MWEB coins, and the
  chain continues to FIXTURE_HEIGHT, with every coinbase spendable by MiniWallet;
- signed transactions, valid at the tip and not in the chain: an MWEB-only
  spend, a conflicting spend of the same MWEB coin, a peg-out to MiniWallet's
  address, and a peg-in.

Run it after a change makes the fixture invalid, then commit the file.

Not part of the functional test suite.
"""
import json

from test_framework.mweb_util import (
    ASSUMEUTXO_MWEB_HDKEY_TPRV,
    FIRST_MWEB_HEIGHT,
    MWEB_FIXTURE_PATH,
    MWEB_VB_START_TIME,
    init_named_assumeutxo_mweb_wallet,
    mine_mweb_fixture_pre_chain,
    mweb_extra_args,
)
from test_framework.test_framework import BitcoinTestFramework
from test_framework.util import assert_equal
from test_framework.wallet import MiniWallet

FIXTURE_HEIGHT = FIRST_MWEB_HEIGHT + 8
PEGIN_COIN_AMOUNT = 10


class GenerateMWEBFixture(BitcoinTestFramework):
    def set_test_params(self):
        self.setup_clean_chain = True
        self.num_nodes = 1
        self.extra_args = mweb_extra_args([])

    def skip_test_if_missing_module(self):
        self.skip_if_no_wallet()

    def build(self, wallet, inputs, outputs):
        res = wallet.send(outputs=outputs, options={"inputs": inputs, "add_inputs": False, "add_to_wallet": False})
        assert res["complete"]
        return {"txid": self.nodes[0].decoderawtransaction(res["hex"])["txid"], "hex": res["hex"]}

    def run_test(self):
        node = self.nodes[0]
        mocktime = MWEB_VB_START_TIME
        # The wallet skips blocks older than its birth time.
        node.setmocktime(mocktime)
        wallet = init_named_assumeutxo_mweb_wallet(self, node=0, wallet_name="fixture",
                                                   hdkey_tprv=ASSUMEUTXO_MWEB_HDKEY_TPRV, import_coinbase=False)
        miniwallet_address = MiniWallet(node).get_address()
        funding_address = wallet.getnewaddress(address_type="bech32")

        self.log.info("Mine the pre-MWEB blocks")
        mine_mweb_fixture_pre_chain(self, node, mocktime=mocktime, funding_address=funding_address)
        pre_mweb_tip = node.getbestblockhash()

        self.log.info("Peg four MWEB coins in and mine the first MWEB block")
        pegin_outputs = [{wallet.getnewaddress(address_type="mweb"): PEGIN_COIN_AMOUNT} for _ in range(4)]
        funding_coin = wallet.listunspent()[0]
        wallet.send(outputs=pegin_outputs, options={"inputs": [{"txid": funding_coin["txid"], "vout": funding_coin["vout"]}]})
        self.generatetoaddress(node, FIXTURE_HEIGHT - node.getblockcount(), miniwallet_address, sync_fun=self.no_op)
        assert_equal(node.getblockcount(), FIXTURE_HEIGHT)
        assert node.getblock(node.getblockhash(FIRST_MWEB_HEIGHT), 2).get("mweb")

        coins = sorted((u for u in wallet.listunspent() if u.get("output_id") and u["amount"] == PEGIN_COIN_AMOUNT),
                       key=lambda u: u["output_id"])
        assert_equal(len(coins), 4)
        l1_coin = next(u for u in wallet.listunspent() if not u.get("output_id"))

        self.log.info("Sign the loose transactions")
        coin_a = {"output_id": coins[0]["output_id"]}
        coin_b = {"output_id": coins[1]["output_id"]}
        txs = {
            "mweb_to_mweb": self.build(wallet, [coin_a], [{wallet.getnewaddress(address_type="mweb"): 5}]),
            "mweb_conflict": self.build(wallet, [coin_a], [{wallet.getnewaddress(address_type="mweb"): 4}]),
            "pegout": self.build(wallet, [coin_b], [{miniwallet_address: 3}]),
            "pegin": self.build(wallet, [{"txid": l1_coin["txid"], "vout": l1_coin["vout"]}],
                                [{wallet.getnewaddress(address_type="mweb"): 7}]),
        }
        for tx in txs.values():
            assert_equal(node.testmempoolaccept([tx["hex"]])[0]["allowed"], True)

        fixture = {
            "comment": "Generated by test/functional/mweb_generate_fixture.py; see load_mweb_fixture.",
            "mocktime": mocktime,
            "funding_address": funding_address,
            "pre_mweb_tip": pre_mweb_tip,
            "tip": node.getbestblockhash(),
            "mweb_coins": [c["output_id"] for c in coins],
            "pegout_address": miniwallet_address,
            "blocks": [node.getblock(node.getblockhash(h), 0) for h in range(FIRST_MWEB_HEIGHT, FIXTURE_HEIGHT + 1)],
            "txs": txs,
        }
        with open(MWEB_FIXTURE_PATH, "w", encoding="utf8") as f:
            json.dump(fixture, f, indent=1)
            f.write("\n")
        self.log.info(f"Wrote {MWEB_FIXTURE_PATH}")


if __name__ == '__main__':
    GenerateMWEBFixture(__file__).main()
